/**
 * ── Tematické zásoby pre Impostera ──────────────────────────────────────────
 *
 * Nahrádzajú pôvodnú kategóriu „Situácie“, ktorá vznikala krížením šablón
 * („Kresba psa“, „Fotografia psa“, …). Tá dávala tisíce položiek, ale hrateľné
 * neboli — slová sa opakovali v obmenách a partia nemala o čom diskutovať.
 *
 * Každá nápoveda je napísaná osobitne pre svoje slovo. Má byť pravdivou,
 * prirodzenou asociáciou, z ktorej vie imposter vytvoriť prvú odpoveď, ale nie
 * definíciou, synonymom, priamou mechanikou ani unikátnym detailom, ktorý by
 * tajné slovo hneď prezradil. Uprednostňuje sa jedno prirodzené slovenské slovo;
 * dve slová sú prípustné iba vtedy, keď jednoslovná asociácia nestačí.
 *
 * Každá kategória má 50 párov, rovnako ako ručne písané kategórie v
 * `categories.ts`.
 */


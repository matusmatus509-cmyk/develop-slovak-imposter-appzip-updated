function uniqueStrings(items: string[]) {
  return [...new Set(items)];
}

function exact<T>(
  label: string,
  items: T[],
  count: number,
  key?: (item: T) => string
) {
  if (items.length !== count)
    throw new Error(
      `${label} must contain exactly ${count} entries, got ${items.length}.`
    );
  if (key && new Set(items.map(key)).size !== count)
    throw new Error(`${label} must contain unique entries.`);
  return items;
}

